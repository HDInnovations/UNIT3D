test('thank returns an ok response when user thanks a torrent', function (): void {
    Notification::fake();

    $user = User::factory()->create();
    $uploader = User::factory()->create();
    $torrent = Torrent::factory()->for($uploader)->create();

    $response = $this->actingAs($user, AuthGuard::API->value)
        ->postJson(route('api.torrents.thank', ['id' => $torrent->id]));

    $response->assertOk()
        ->assertJson([
            'success' => true,
            'message' => 'Your thank was successfully applied!',
        ]);

    $this->assertDatabaseHas('thanks', [
        'user_id'    => $user->id,
        'torrent_id' => $torrent->id,
    ]);

    Notification::assertSentTo($uploader, NewThank::class);
});

test('thank returns an error when user tries to thank their own upload', function (): void {
    $uploader = User::factory()->create();
    $torrent = Torrent::factory()->for($uploader)->create();

    $response = $this->actingAs($uploader, AuthGuard::API->value)
        ->postJson(route('api.torrents.thank', ['id' => $torrent->id]));

    $response->assertStatus(422)
        ->assertJson([
            'success' => false,
            'message' => 'You cannot thank your own content!',
        ]);
});

test('thank returns an error when user has already thanked', function (): void {
    $user = User::factory()->create();
    $uploader = User::factory()->create();
    $torrent = Torrent::factory()->for($uploader)->create();

    Thank::factory()->create([
        'user_id'    => $user->id,
        'torrent_id' => $torrent->id,
    ]);

    $response = $this->actingAs($user, AuthGuard::API->value)
        ->postJson(route('api.torrents.thank', ['id' => $torrent->id]));

    $response->assertStatus(422)
        ->assertJson([
            'success' => false,
            'message' => 'You have already thanked!',
        ]);
});
